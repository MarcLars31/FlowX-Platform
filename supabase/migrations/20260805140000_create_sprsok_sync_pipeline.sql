drop policy if exists sprsok_products_authenticated_read on public.sprsok_products;
create policy sprsok_products_authenticated_read on public.sprsok_products
for select to authenticated using (
  exists (
    select 1 from public.sprsok_product_search_index search_index
    where search_index.product_id = sprsok_products.id
      and search_index.is_visible
  )
);

drop policy if exists sprsok_search_index_authenticated_read
  on public.sprsok_product_search_index;
create policy sprsok_search_index_authenticated_read
on public.sprsok_product_search_index
for select to authenticated using (is_visible);

do $$
declare table_name text;
begin
  foreach table_name in array array[
    'sprsok_sync_runs', 'sprsok_sync_page_logs', 'sprsok_sync_errors',
    'sprsok_source_snapshot', 'sprsok_review_queue',
    'sprsok_datasheet_discovery_queue', 'sprsok_product_search_index'
  ] loop
    execute format('drop policy if exists sprsok_platform_admin_all on public.%I', table_name);
    execute format(
      'create policy sprsok_platform_admin_all on public.%I for all to authenticated using (public.is_platform_admin()) with check (public.is_platform_admin())',
      table_name
    );
  end loop;
end;
$$;

