create or replace function public.refresh_sprsok_product_search_index()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog
as $$
declare
  visible boolean;
  reason text;
begin
  visible := new.source_status not in ('inactive', 'deleted')
    and nullif(btrim(new.sin), '') is not null
    and nullif(btrim(new.leverandor), '') is not null
    and nullif(btrim(new.type), '') is not null
    and cardinality(new.validation_errors) = 0;
  reason := case
    when new.source_status in ('inactive', 'deleted') then 'source_status_' || new.source_status
    when nullif(btrim(new.sin), '') is null then 'missing_article_number'
    when nullif(btrim(new.leverandor), '') is null then 'missing_supplier'
    when nullif(btrim(new.type), '') is null then 'missing_product_name'
    when cardinality(new.validation_errors) > 0 then array_to_string(new.validation_errors, ',')
    else null
  end;

  insert into public.sprsok_product_search_index (
    product_id,
    source_record_key,
    normalized_article_number,
    search_document,
    is_visible,
    hidden_reason,
    indexed_at
  ) values (
    new.id,
    new.source_record_key,
    public.normalize_sprsok_article(new.sin),
    lower(concat_ws(' ', new.sin, new.leverandor, new.type, new.utforelse, new.k_verdi, new.rti)),
    visible,
    reason,
    now()
  )
  on conflict (product_id) do update
    set source_record_key = excluded.source_record_key,
        normalized_article_number = excluded.normalized_article_number,
        search_document = excluded.search_document,
        is_visible = excluded.is_visible,
        hidden_reason = excluded.hidden_reason,
        indexed_at = excluded.indexed_at;
  return new;
end;
$$;

drop trigger if exists refresh_sprsok_product_search_index_trigger
  on public.sprsok_products;
create trigger refresh_sprsok_product_search_index_trigger
after insert or update of
  source_record_key, sin, leverandor, type, utforelse, k_verdi, rti,
  source_status, validation_errors
on public.sprsok_products
for each row execute function public.refresh_sprsok_product_search_index();

insert into public.sprsok_product_search_index (
  product_id, source_record_key, normalized_article_number, search_document,
  is_visible, hidden_reason, indexed_at
)
select
  product.id,
  product.source_record_key,
  public.normalize_sprsok_article(product.sin),
  lower(concat_ws(' ', product.sin, product.leverandor, product.type, product.utforelse, product.k_verdi, product.rti)),
  product.source_status not in ('inactive', 'deleted')
    and nullif(btrim(product.sin), '') is not null
    and nullif(btrim(product.leverandor), '') is not null
    and nullif(btrim(product.type), '') is not null
    and cardinality(product.validation_errors) = 0,
  case
    when product.source_status in ('inactive', 'deleted') then 'source_status_' || product.source_status
    when nullif(btrim(product.sin), '') is null then 'missing_article_number'
    when nullif(btrim(product.leverandor), '') is null then 'missing_supplier'
    when nullif(btrim(product.type), '') is null then 'missing_product_name'
    when cardinality(product.validation_errors) > 0 then array_to_string(product.validation_errors, ',')
    else null
  end,
  now()
from public.sprsok_products product
on conflict (product_id) do update
set source_record_key = excluded.source_record_key,
    normalized_article_number = excluded.normalized_article_number,
    search_document = excluded.search_document,
    is_visible = excluded.is_visible,
    hidden_reason = excluded.hidden_reason,
    indexed_at = excluded.indexed_at;

