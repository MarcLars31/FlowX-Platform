create or replace function public.begin_sprsok_sync(
  p_resume boolean default false,
  p_dry_run boolean default false
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog
as $$
declare
  selected_run public.sprsok_sync_runs%rowtype;
begin
  if p_resume then
    select * into selected_run
    from public.sprsok_sync_runs
    where source = 'sprsok' and status in ('paused', 'failed') and dry_run = p_dry_run
    order by updated_at desc
    limit 1
    for update skip locked;
  end if;
  if selected_run.id is null then
    insert into public.sprsok_sync_runs (status, dry_run)
    values ('running', p_dry_run)
    returning * into selected_run;
  else
    update public.sprsok_sync_runs
      set status = 'running', completed_at = null, updated_at = now()
    where id = selected_run.id
    returning * into selected_run;
  end if;
  return jsonb_build_object(
    'runId', selected_run.id,
    'checkpoint', selected_run.checkpoint,
    'counts', jsonb_build_object(
      'sourceTotal', selected_run.source_total,
      'pages', selected_run.pages_received,
      'received', selected_run.records_received,
      'accepted', selected_run.accepted_count,
      'rejected', selected_run.rejected_count,
      'created', selected_run.created_count,
      'updated', selected_run.updated_count,
      'unchanged', selected_run.unchanged_count,
      'review', selected_run.review_count,
      'errors', selected_run.error_count,
      'datasheetQueueErrors', selected_run.datasheet_queue_error_count
    )
  );
end;
$$;

create or replace function public.upsert_sprsok_product(
  p_run_id uuid,
  p_record jsonb,
  p_dry_run boolean default false
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog
as $$
declare
  record_key text := nullif(p_record ->> 'source_record_key', '');
  existing public.sprsok_products%rowtype;
  saved public.sprsok_products%rowtype;
  errors text[] := coalesce(
    array(select jsonb_array_elements_text(coalesce(p_record -> 'validation_errors', '[]'::jsonb))),
    '{}'::text[]
  );
  outcome text;
begin
  if record_key is null then
    record_key := 'invalid:' || md5(p_record::text);
  end if;

  insert into public.sprsok_source_snapshot (
    run_id, source_record_key, external_product_id, supplier,
    manufacturer_article_number, product_name, variant, validation_errors, source_data
  ) values (
    p_run_id, record_key, p_record ->> 'external_product_id', p_record ->> 'supplier',
    p_record ->> 'manufacturer_article_number', p_record ->> 'product_name',
    p_record ->> 'variant', errors, coalesce(p_record -> 'source_data', '{}'::jsonb)
  ) on conflict (run_id, source_record_key) do update
    set source_data = excluded.source_data,
        validation_errors = excluded.validation_errors,
        observed_at = now();

  if nullif(p_record ->> 'source_record_key', '') is null then
    if not p_dry_run then
      insert into public.sprsok_review_queue (
        source_record_key, external_product_id, supplier,
        manufacturer_article_number, variant, validation_errors, source_data
      ) values (
        record_key, p_record ->> 'external_product_id', p_record ->> 'supplier',
        p_record ->> 'manufacturer_article_number', p_record ->> 'variant',
        errors, coalesce(p_record -> 'source_data', '{}'::jsonb)
      ) on conflict (source_record_key) do update
        set validation_errors = excluded.validation_errors,
            source_data = excluded.source_data,
            status = 'pending',
            last_seen_at = now();
    end if;
    return jsonb_build_object('outcome', 'review');
  end if;

  select * into existing
  from public.sprsok_products
  where source = 'sprsok' and source_record_key = record_key;

  if existing.id is null then
    outcome := case when cardinality(errors) > 0 then 'review' else 'created' end;
  elsif existing.source_data = coalesce(p_record -> 'source_data', '{}'::jsonb)
    and existing.validation_errors = errors then
    outcome := case when cardinality(errors) > 0 then 'review' else 'unchanged' end;
  else
    outcome := case when cardinality(errors) > 0 then 'review' else 'updated' end;
  end if;
  if p_dry_run then return jsonb_build_object('outcome', outcome); end if;

  insert into public.sprsok_products (
    source, source_record_key, external_product_id, supplier,
    manufacturer_article_number, product_name, variant, category, source_status,
    sin, leverandor, type, utforelse, k_verdi, rti, datablad,
    last_synced_at, source_data, import_metadata, validation_errors
  ) values (
    'sprsok', record_key, p_record ->> 'external_product_id', p_record ->> 'supplier',
    p_record ->> 'manufacturer_article_number', p_record ->> 'product_name',
    p_record ->> 'variant', p_record ->> 'category', coalesce(p_record ->> 'source_status', 'active'),
    p_record ->> 'sin', p_record ->> 'leverandor', p_record ->> 'type',
    p_record ->> 'utforelse', p_record ->> 'k_verdi', p_record ->> 'rti', p_record ->> 'datablad',
    now(), coalesce(p_record -> 'source_data', '{}'::jsonb),
    jsonb_build_object('last_run_id', p_run_id), errors
  )
  on conflict (source, source_record_key) do update set
    external_product_id = case when 'external_product_id' = any(public.sprsok_products.manual_locked_fields)
      then public.sprsok_products.external_product_id else excluded.external_product_id end,
    supplier = case when 'supplier' = any(public.sprsok_products.manual_locked_fields)
      then public.sprsok_products.supplier else excluded.supplier end,
    manufacturer_article_number = case when 'manufacturer_article_number' = any(public.sprsok_products.manual_locked_fields)
      then public.sprsok_products.manufacturer_article_number else excluded.manufacturer_article_number end,
    product_name = case when 'product_name' = any(public.sprsok_products.manual_locked_fields)
      then public.sprsok_products.product_name else excluded.product_name end,
    variant = case when 'variant' = any(public.sprsok_products.manual_locked_fields)
      then public.sprsok_products.variant else excluded.variant end,
    category = case when 'category' = any(public.sprsok_products.manual_locked_fields)
      then public.sprsok_products.category else excluded.category end,
    source_status = excluded.source_status,
    sin = case when 'sin' = any(public.sprsok_products.manual_locked_fields)
      then public.sprsok_products.sin else excluded.sin end,
    leverandor = case when 'leverandor' = any(public.sprsok_products.manual_locked_fields)
      then public.sprsok_products.leverandor else excluded.leverandor end,
    type = case when 'type' = any(public.sprsok_products.manual_locked_fields)
      then public.sprsok_products.type else excluded.type end,
    utforelse = case when 'utforelse' = any(public.sprsok_products.manual_locked_fields)
      then public.sprsok_products.utforelse else excluded.utforelse end,
    k_verdi = case when 'k_verdi' = any(public.sprsok_products.manual_locked_fields)
      then public.sprsok_products.k_verdi else excluded.k_verdi end,
    rti = case when 'rti' = any(public.sprsok_products.manual_locked_fields)
      then public.sprsok_products.rti else excluded.rti end,
    datablad = case when 'datablad' = any(public.sprsok_products.manual_locked_fields)
      then public.sprsok_products.datablad else excluded.datablad end,
    last_synced_at = now(),
    source_data = excluded.source_data,
    import_metadata = public.sprsok_products.import_metadata || excluded.import_metadata,
    validation_errors = excluded.validation_errors,
    updated_at = now()
  returning * into saved;

  if cardinality(errors) > 0 then
    insert into public.sprsok_review_queue (
      product_id, source_record_key, external_product_id, supplier,
      manufacturer_article_number, variant, validation_errors, source_data
    ) values (
      saved.id, record_key, saved.external_product_id, saved.supplier,
      saved.manufacturer_article_number, saved.variant, errors, saved.source_data
    ) on conflict (source_record_key) do update
      set product_id = excluded.product_id,
          validation_errors = excluded.validation_errors,
          source_data = excluded.source_data,
          status = 'pending',
          last_seen_at = now();
  end if;
  return jsonb_build_object('outcome', outcome, 'productId', saved.id);
end;
$$;

create or replace function public.queue_sprsok_datasheet(
  p_run_id uuid,
  p_source_record_key text
)
returns void
language plpgsql
security definer
set search_path = pg_catalog
as $$
declare selected_product public.sprsok_products%rowtype;
begin
  select * into selected_product from public.sprsok_products
  where source = 'sprsok' and source_record_key = p_source_record_key;
  if selected_product.id is null or nullif(selected_product.datablad, '') is not null then return; end if;
  insert into public.sprsok_datasheet_discovery_queue (product_id, source_record_key)
  values (selected_product.id, selected_product.source_record_key)
  on conflict (product_id) do update
    set status = case
      when public.sprsok_datasheet_discovery_queue.status in ('found', 'processing')
      then public.sprsok_datasheet_discovery_queue.status else 'pending' end,
        updated_at = now();
end;
$$;

create or replace function public.record_sprsok_sync_page(
  p_run_id uuid,
  p_checkpoint jsonb,
  p_received integer,
  p_next_checkpoint jsonb,
  p_source_total integer default null
)
returns void
language plpgsql
security definer
set search_path = pg_catalog
as $$
begin
  insert into public.sprsok_sync_page_logs (
    run_id, page_number, cursor, offset_value, records_received,
    next_cursor, next_offset, source_total
  ) values (
    p_run_id, coalesce((p_checkpoint ->> 'pageNumber')::integer, 1),
    p_checkpoint ->> 'cursor', coalesce((p_checkpoint ->> 'offset')::integer, 0),
    p_received, p_next_checkpoint ->> 'cursor',
    (p_next_checkpoint ->> 'offset')::integer, p_source_total
  ) on conflict (run_id, page_number) do update
    set records_received = excluded.records_received,
        next_cursor = excluded.next_cursor,
        next_offset = excluded.next_offset,
        source_total = excluded.source_total,
        received_at = now();
  update public.sprsok_sync_runs
  set checkpoint = coalesce(p_next_checkpoint, p_checkpoint),
      source_total = coalesce(p_source_total, source_total),
      pages_received = pages_received + 1,
      records_received = records_received + p_received,
      updated_at = now()
  where id = p_run_id;
end;
$$;

