create or replace function public.normalize_sprsok_identity(value text)
returns text
language sql
immutable
set search_path = pg_catalog
as $$
  select lower(regexp_replace(btrim(coalesce(value, '')), '[[:space:]]+', ' ', 'g'));
$$;

create or replace function public.normalize_sprsok_article(value text)
returns text
language sql
immutable
set search_path = pg_catalog
as $$
  select upper(regexp_replace(btrim(coalesce(value, '')), '[[:space:]_./-]+', '', 'g'));
$$;

