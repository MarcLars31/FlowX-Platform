create or replace function public.finish_sprsok_sync(
  p_run_id uuid,
  p_status text,
  p_checkpoint jsonb,
  p_counts jsonb
)
returns void
language plpgsql
security definer
set search_path = pg_catalog
as $$
begin
  if p_status not in ('completed', 'paused', 'failed') then
    raise exception 'Invalid Sprsok sync status';
  end if;
  update public.sprsok_sync_runs set
    status = p_status,
    checkpoint = coalesce(p_checkpoint, checkpoint),
    source_total = coalesce((p_counts ->> 'sourceTotal')::integer, source_total),
    pages_received = coalesce((p_counts ->> 'pages')::integer, pages_received),
    records_received = coalesce((p_counts ->> 'received')::integer, records_received),
    accepted_count = coalesce((p_counts ->> 'accepted')::integer, accepted_count),
    rejected_count = coalesce((p_counts ->> 'rejected')::integer, rejected_count),
    created_count = coalesce((p_counts ->> 'created')::integer, created_count),
    updated_count = coalesce((p_counts ->> 'updated')::integer, updated_count),
    unchanged_count = coalesce((p_counts ->> 'unchanged')::integer, unchanged_count),
    review_count = coalesce((p_counts ->> 'review')::integer, review_count),
    error_count = coalesce((p_counts ->> 'errors')::integer, error_count),
    datasheet_queue_error_count = coalesce((p_counts ->> 'datasheetQueueErrors')::integer, datasheet_queue_error_count),
    completed_at = case when p_status in ('completed', 'failed') then now() else null end,
    updated_at = now()
  where id = p_run_id;
end;
$$;

create or replace function public.reindex_sprsok_products(
  p_source_record_keys text[] default null,
  p_dry_run boolean default true
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog
as $$
declare candidate_count integer;
begin
  select count(*) into candidate_count
  from public.sprsok_products
  where source = 'sprsok'
    and (p_source_record_keys is null or source_record_key = any(p_source_record_keys));
  if p_dry_run then
    return jsonb_build_object('candidates', candidate_count, 'indexed', 0);
  end if;

  insert into public.sprsok_product_search_index (
    product_id, source_record_key, normalized_article_number, search_document,
    is_visible, hidden_reason, indexed_at
  )
  select
    product.id, product.source_record_key, public.normalize_sprsok_article(product.sin),
    lower(concat_ws(' ', product.sin, product.leverandor, product.type, product.utforelse, product.k_verdi, product.rti)),
    product.source_status not in ('inactive', 'deleted')
      and nullif(btrim(product.sin), '') is not null
      and nullif(btrim(product.leverandor), '') is not null
      and nullif(btrim(product.type), '') is not null
      and cardinality(product.validation_errors) = 0,
    case
      when product.source_status in ('inactive', 'deleted') then 'source_status_' || product.source_status
      when nullif(btrim(product.sin), '') is null then 'missing_article_number'
      when nullif(btrim(product.leverandor), '') is null then 'missing_supplier'
      when nullif(btrim(product.type), '') is null then 'missing_product_name'
      when cardinality(product.validation_errors) > 0 then array_to_string(product.validation_errors, ',')
      else null
    end,
    now()
  from public.sprsok_products product
  where product.source = 'sprsok'
    and (p_source_record_keys is null or product.source_record_key = any(p_source_record_keys))
  on conflict (product_id) do update set
    source_record_key = excluded.source_record_key,
    normalized_article_number = excluded.normalized_article_number,
    search_document = excluded.search_document,
    is_visible = excluded.is_visible,
    hidden_reason = excluded.hidden_reason,
    indexed_at = excluded.indexed_at;
  return jsonb_build_object('candidates', candidate_count, 'indexed', candidate_count);
end;
$$;

create or replace view public.sprsok_reconciliation_issues
with (security_invoker = true)
as
with latest_complete_run as (
  select id from public.sprsok_sync_runs
  where source = 'sprsok' and status = 'completed' and not dry_run
  order by completed_at desc nulls last limit 1
)
select
  'missing_database'::text as issue_type,
  snapshot.source_record_key,
  null::bigint as product_id,
  snapshot.external_product_id,
  snapshot.supplier,
  snapshot.manufacturer_article_number,
  snapshot.variant,
  'Source product is missing in database.'::text as reason,
  snapshot.run_id,
  snapshot.observed_at as detected_at
from public.sprsok_source_snapshot snapshot
join latest_complete_run latest on latest.id = snapshot.run_id
left join public.sprsok_products product
  on product.source = 'sprsok' and product.source_record_key = snapshot.source_record_key
where product.id is null
union all
select
  'missing_index', product.source_record_key, product.id, product.external_product_id,
  product.leverandor, product.sin, product.utforelse,
  'Database product is missing in search index.', null, now()
from public.sprsok_products product
left join public.sprsok_product_search_index index on index.product_id = product.id
where product.source = 'sprsok' and index.product_id is null
union all
select
  'hidden_filter', product.source_record_key, product.id, product.external_product_id,
  product.leverandor, product.sin, product.utforelse,
  coalesce(index.hidden_reason, 'Hidden by search visibility rule.'), null, index.indexed_at
from public.sprsok_products product
join public.sprsok_product_search_index index on index.product_id = product.id
where product.source = 'sprsok' and not index.is_visible
union all
select
  'failed_import', error.source_record_key, null, null, null, null, null,
  error.error_message, error.run_id, error.created_at
from public.sprsok_sync_errors error
where error.resolved_at is null and error.error_scope in ('product','reconcile','index');

